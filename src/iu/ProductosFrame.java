    private void actualizarTabla(Collection<Producto> productos) {
        modelo.setRowCount(0);
        if (productos != null) {
            for (Producto p : productos) {
                modelo.addRow(new Object[]{
                    p.getId(), p.getNombre(), "$" + p.getPrecio(), p.getStock(), p.getCategoria()
                });
            }
        }
    }
    
    private void limpiarFormulario() {
        txtID.setText("");
        txtName.setText("");
        txtPrice.setText("");
        txtStock.setText("");
        cbCategorias.setSelectedIndex(0);
        txtID.setEditable(true); // Desbloquea el ID para nuevas inserciones
    }
    
    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {                                     
        int filaSeleccionada = jTable1.getSelectedRow();
        if (filaSeleccionada >= 0) {
            String id = modelo.getValueAt(filaSeleccionada, 0).toString();
            String nombre = modelo.getValueAt(filaSeleccionada, 1).toString();
            String precio = modelo.getValueAt(filaSeleccionada, 2).toString().replace("$", "");
            String stock = modelo.getValueAt(filaSeleccionada, 3).toString();
            String categoria = modelo.getValueAt(filaSeleccionada, 4).toString();

            txtID.setText(id);
            txtID.setEditable(false); // Evitamos la modificación del ID primario accidental
            txtName.setText(nombre);
            txtPrice.setText(precio);
            txtStock.setText(stock);
            cbCategorias.setSelectedItem(categoria);
        }
    }
    
