    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
            int id = Integer.parseInt(txtID.getText().trim());
            String nombre = txtName.getText().trim();
            double precio = Double.parseDouble(txtPrice.getText().trim());
            int stock = Integer.parseInt(txtStock.getText().trim());
            String categoria = cbCategorias.getSelectedItem().toString();

            if (nombre.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor introduce el nombre del producto.", "Validación", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Producto nuevo = new Producto(id, nombre, precio, stock, categoria);
            productoServicio.registrar(nuevo); 
            
            actualizarTabla(productoServicio.listarTodos());
            limpiarFormulario();
            JOptionPane.showMessageDialog(this, "¡Producto agregado exitosamente!", "Éxito", JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Revisa los campos numéricos (ID, Precio y Stock).", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) { 
            JOptionPane.showMessageDialog(this, e.getMessage(), "Alerta de Negocio", JOptionPane.WARNING_MESSAGE);
        } 
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int filaSeleccionada = jTable1.getSelectedRow();
        if (filaSeleccionada >= 0) {
            int id = (int) jTable1.getValueAt(filaSeleccionada, 0);
            int confirmacion = JOptionPane.showConfirmDialog(this, "¿Estás seguro de eliminar este dulce?", "Confirmación", JOptionPane.YES_NO_OPTION);
            
            if (confirmacion == JOptionPane.YES_OPTION) {
                try {
                    productoServicio.eliminar(id); 
                    
                    actualizarTabla(productoServicio.listarTodos());
                    limpiarFormulario();
                    JOptionPane.showMessageDialog(this, "Producto borrado.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                } catch (EntidadNoEncontradaException e) {
                    JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Selecciona un renglón de la tabla para eliminar.", "Atención", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int filaSeleccionada = jTable1.getSelectedRow();
        if (filaSeleccionada >= 0) {
            try {
                int id = (int) jTable1.getValueAt(filaSeleccionada, 0); 
                String nombre = txtName.getText().trim();
                double precio = Double.parseDouble(txtPrice.getText().trim().replace("$", ""));
                int stock = Integer.parseInt(txtStock.getText().trim());
                String categoria = cbCategorias.getSelectedItem().toString();

                Producto modificado = new Producto(id, nombre, precio, stock, categoria);
                
                productoServicio.actualizar(id, modificado); 
                
                actualizarTabla(productoServicio.listarTodos());
                limpiarFormulario();
                JOptionPane.showMessageDialog(this, "Datos actualizados correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Verifica los números de Precio y Stock.", "Error", JOptionPane.ERROR_MESSAGE);
            } catch (EntidadNoEncontradaException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Elige primero un producto en la tabla para editar.", "Atención", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String busqueda = txtBuscar.getText().trim();
        if (busqueda.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digita un ID en el campo de búsqueda.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            int id = Integer.parseInt(busqueda);
            
            Producto p = productoServicio.buscarPorId(id); 
            
            txtID.setText(String.valueOf(p.getId()));
            txtID.setEditable(false); 
            txtName.setText(p.getNombre());
            txtPrice.setText(String.valueOf(p.getPrecio()));
            txtStock.setText(String.valueOf(p.getStock()));
            cbCategorias.setSelectedItem(p.getCategoria());
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El código de búsqueda debe ser un número entero.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (EntidadNoEncontradaException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "No Registrado", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

